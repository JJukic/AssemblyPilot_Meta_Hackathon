// Writes CLIP_MAPPING.md from the manifest so that the mapping cannot drift from the edit.
import { writeFileSync } from "node:fs";
import { browserShots, completionShots, exclusions, introShots, problemShot, productShots, scenes, solveShots, totalFrames, FPS, workflowShots, type Shot } from "../src/manifest.ts";

const groups: [string, Shot[]][] = [
  ["Intro", introShots], ["Problem", [problemShot]], ["Product", productShots],
  ["Assembly workflow", [...workflowShots.before, ...workflowShots.after]], ["Browser", browserShots], ["Problem solving", solveShots], ["Completion", completionShots],
];
const mmss = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
const lines = ["# Clip mapping", "", "Generated by `npm run mapping` from `src/manifest.ts`. Do not edit by hand.", "",
  `Total: ${(totalFrames / FPS).toFixed(1)} s, ${totalFrames} frames at ${FPS} fps.`, "", "## Scenes", "", "| Scene | Seconds |", "| --- | --- |",
  ...scenes.map((s) => `| ${s.id} | ${s.dur.toFixed(1)} |`), "", "## Used shots", "", "| Scene | Shot | File | Source range | Speed | On-screen text |", "| --- | --- | --- | --- | --- | --- |"];
for (const [name, shots] of groups) for (const s of shots) {
  const still = s.src.endsWith(".jpg");
  lines.push(`| ${name} | ${s.id} | \`${s.src.replace("footage/hololens/", "").replace("footage/browser/", "")}\` | ${still ? "still" : `${mmss(s.from)}–${mmss(s.from + s.dur * (s.rate ?? 1))}`} | ${s.rate ?? 1}× | ${s.caption ?? ""}${s.note ? ` (${s.note})` : ""} |`);
}
lines.push("| Assembly workflow | triptych | `shot1.jpg`, `shot3.jpg`, `shot4.jpg` | crops | | Reference, capture, result |", "", "## Not used", "", "| File | Range | Reason |", "| --- | --- | --- |",
  ...exclusions.map((e) => `| \`${e.file.replace("footage/hololens/", "")}\` | ${e.range} | ${e.reason} |`), "");
writeFileSync("CLIP_MAPPING.md", lines.join("\n"));
